// Klangauge dil durumu ve arayüz çevirileri.
// lang değeri localStorage'da saklanır; t(key) anlık dile göre metin döner.
import { ref } from 'vue'

export const lang = ref('tr')
try {
  const saved = localStorage.getItem('klangauge-lang')
  if (saved && ['tr', 'de', 'en'].includes(saved)) lang.value = saved
} catch {
  /* localStorage kullanılamayabilir */
}

export function setLang(l) {
  lang.value = l
  document.documentElement.lang = l
  try {
    localStorage.setItem('klangauge-lang', l)
  } catch {
    /* yoksay */
  }
}

